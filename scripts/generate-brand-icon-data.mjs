import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const icons = [
  // Compact transparent derivative of the supplied C5B reference. The full
  // reference remains in assets for provenance; the tab icon remains untouched.
  ['REVERIE_RELAY_SIDEBAR_ICON_URL', 'relay-sidebar-icon-compact-white.png'],
  ['REVERIE_RELAY_TAB_ICON_URL', 'relay-tab-icon-APPROVED-fullcolor-portal.png'],
]

const dataUrl = file => `data:image/png;base64,${readFileSync(resolve(root, 'assets', file)).toString('base64')}`
const lines = [
  '// Generated by scripts/generate-brand-icon-data.mjs from the exact approved assets.',
  '// Do not hand-edit; regenerate after replacing an approved source asset.',
  ...icons.map(([name, file]) => `export const ${name}: string = ${JSON.stringify(dataUrl(file))}`),
  'export const REVERIE_RELAY_ICON_DATA_URL: string = REVERIE_RELAY_TAB_ICON_URL',
  '',
]

writeFileSync(resolve(root, 'src', 'brandIconData.generated.ts'), lines.join('\n'))
